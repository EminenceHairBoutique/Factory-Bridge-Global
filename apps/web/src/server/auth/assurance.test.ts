import { describe, expect, it } from "vitest";
import { QR_MAX_CHARS, aalFromAccessToken, hasVerifiedTotp, totpQrDataUrl } from "./assurance";

const b64 = (v: unknown) => Buffer.from(JSON.stringify(v)).toString("base64url");
const jwt = (payload: unknown) => `${b64({ alg: "HS256", typ: "JWT" })}.${b64(payload)}.sig`;

describe("aalFromAccessToken (claim of a token Supabase Auth already validated)", () => {
  it("reads aal2 only when the claim is exactly 'aal2'", () => {
    expect(aalFromAccessToken(jwt({ sub: "u", aal: "aal2" }))).toBe("aal2");
    expect(aalFromAccessToken(jwt({ sub: "u", aal: "aal1" }))).toBe("aal1");
    expect(aalFromAccessToken(jwt({ sub: "u", aal: "AAL2" }))).toBe("aal1");
    expect(aalFromAccessToken(jwt({ sub: "u" }))).toBe("aal1");
    expect(aalFromAccessToken(jwt({ sub: "u", aal: ["aal2"] }))).toBe("aal1");
  });

  it("is aal1 for anything that is not a three-part token with a JSON object payload", () => {
    for (const bad of [
      undefined,
      null,
      42,
      "",
      "a.b",
      "a.b.c.d",
      `x.${b64("aal2")}.y`,
      `x.${b64(["aal2"])}.y`,
      "x.%%%.y",
      `x.${"A".repeat(20_000)}.y`,
    ]) {
      expect(aalFromAccessToken(bad), String(bad).slice(0, 20)).toBe("aal1");
    }
  });
});

describe("hasVerifiedTotp", () => {
  it("counts verified TOTP factors only", () => {
    expect(hasVerifiedTotp([{ factor_type: "totp", status: "verified" }])).toBe(true);
    expect(hasVerifiedTotp([{ factor_type: "totp", status: "unverified" }])).toBe(false);
    expect(hasVerifiedTotp([{ factor_type: "phone", status: "verified" }])).toBe(false);
    expect(hasVerifiedTotp([])).toBe(false);
    expect(hasVerifiedTotp(undefined)).toBe(false);
    expect(hasVerifiedTotp(null)).toBe(false);
  });
});

describe("totpQrDataUrl (Supabase's enrolment QR code, re-encoded for <img src>)", () => {
  // The shape Supabase Auth returns through supabase-js (checked against the local stack, 2026-11-14).
  const svg =
    '<?xml version="1.0"?>\n<!-- Generated by SVGo -->\n<svg width="219" height="219"\n     xmlns="http://www.w3.org/2000/svg"><rect fill="#000" width="1" height="1"/></svg>\n';

  it("accepts Supabase's data URL (XML declaration and comment before <svg>, ~320 KB) as base64", () => {
    const asBase64 = (v: string) =>
      `data:image/svg+xml;base64,${Buffer.from(v, "utf8").toString("base64")}`;
    const url = totpQrDataUrl(`data:image/svg+xml;utf-8,${svg}`);
    expect(url).toBe(asBase64(svg));
    expect(url).not.toMatch(/[<>"#\s]/);
    expect(totpQrDataUrl("<svg><g/></svg>")).toBe(asBase64("<svg><g/></svg>"));
    // Real codes carry one <rect> per module: about 320 KB.
    const module = '<rect x="0" y="0" width="3" height="3" style="fill:white;stroke:none" />\n';
    const big = svg.replace("</svg>", `${module.repeat(5_000)}</svg>`);
    expect(big.length).toBeGreaterThan(300_000);
    expect(totpQrDataUrl(`data:image/svg+xml;utf-8,${big}`)).toBe(asBase64(big));
  });

  it("refuses anything that is not a whole SVG document", () => {
    for (const bad of [
      undefined,
      null,
      42,
      "",
      "data:image/png;base64,AAAA",
      "data:image/svg+xml;utf-8,<html><svg></svg></html>",
      "data:image/svg+xml;utf-8,<svg>",
      "javascript:alert(1)",
      `<svg>${"x".repeat(QR_MAX_CHARS)}</svg>`,
    ]) {
      expect(totpQrDataUrl(bad), String(bad).slice(0, 30)).toBeUndefined();
    }
  });
});
